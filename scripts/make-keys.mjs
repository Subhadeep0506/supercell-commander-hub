// Reads .env and writes src/config/keys.ts.
//
// A generated module is used instead of react-native-config because it works
// identically under Metro and Vite -- neither bundler needs a native module or
// a plugin to read it.
//
// The output is gitignored. Run via `bun run keys`; `web` and `start` do it first.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config } from 'dotenv';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const env = {};
config({ path: resolve(root, '.env'), processEnv: env, quiet: true });

const GAMES = {
  coc: { key: 'COC_API_KEY', base: 'COC_PROXY_BASE', fallback: 'https://cocproxy.royaleapi.dev' },
  cr: { key: 'CR_API_KEY', base: 'CR_PROXY_BASE', fallback: 'https://proxy.royaleapi.dev' },
  bs: { key: 'BS_API_KEY', base: 'BS_PROXY_BASE', fallback: 'https://bsproxy.royaleapi.dev' },
};

const keys = {};
const hosts = {};
const missing = [];
for (const [game, names] of Object.entries(GAMES)) {
  const key = (env[names.key] ?? '').trim();
  if (!key) missing.push(names.key);
  keys[game] = key;
  hosts[game] = (env[names.base] ?? '').trim() || names.fallback;
}

const out = `// GENERATED by scripts/make-keys.mjs -- do not edit, do not commit.
// Source: .env
export const KEYS = ${JSON.stringify(keys, null, 2)} as const;
export const HOSTS = ${JSON.stringify(hosts, null, 2)} as const;
export const MISSING_KEYS: string[] = ${JSON.stringify(missing)};
`;

const target = resolve(root, 'src/config/keys.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);

if (missing.length) {
  console.warn(`keys: wrote src/config/keys.ts, but these are empty in .env: ${missing.join(', ')}`);
} else {
  console.log('keys: wrote src/config/keys.ts with all three tokens');
}
